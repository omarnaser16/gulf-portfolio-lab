"""Check every ticker in config/investable_universe.yaml has price history on Yahoo Finance.

Writes config/investable_history.yaml (first price date, last price date, date checked) and
prints any problem. All network I/O goes through gpl.data. Run:

    python scripts/verify_universe.py
"""

from datetime import date

import yaml

from gpl.data import INVESTABLE_HISTORY, load_investable, verify_history


def main() -> None:
    today = date.today()
    universe = load_investable()
    results = verify_history(list(universe), today)
    history = {}
    for ticker, record in results.items():
        if "problem" in record:
            print(f"{ticker}: {record['problem']}")
        if "history_from" in record:
            history[ticker] = {
                "history_from": record["history_from"],
                "last_price": record["last_price"],
                "verified": today.isoformat(),
                **({"problem": record["problem"]} if "problem" in record else {}),
            }
    header = (
        "# Generated by scripts/verify_universe.py: first and last price dates on Yahoo Finance\n"
        "# for each security in investable_universe.yaml, and the date that was checked.\n"
    )
    with open(INVESTABLE_HISTORY, "w") as f:
        f.write(header + yaml.safe_dump({"history": history}, sort_keys=True))
    print(f"{len(history)} of {len(universe)} verified; wrote {INVESTABLE_HISTORY.name}")


if __name__ == "__main__":
    main()
